import express from "express";
import dotenv from "dotenv";
import cors from "cors";
import authRoutes from "./routes/auth.routes.js";
import postRoutes from "./routes/post.routes.js";
import followRoutes from "./routes/follow.routes.js";
import likesRoutes from "./routes/like.routes.js";
import aiRoutes from "./routes/ai.routes.js";
import conversationRoutes from "./routes/conv.route.js";
import storyRoutes from "./routes/story.routes.js";
import subscriptionRoutes from "./routes/subscription.routes.js";
import adminRoutes from "./routes/admin.routes.js";
import uploadRoutes, { UPLOAD_DIR } from "./routes/upload.routes.js";
import notificationRoutes from "./routes/notification.routes.js";
dotenv.config();
const app = express();
app.set("trust proxy", Number(process.env.TRUST_PROXY ?? 1)); // Render/Vercel: one proxy hop
const origins = (process.env.CLIENT_URL || "http://localhost:3000,https://instagram-clone-pink.vercel.app").split(",").map((s) => s.trim());
app.use(cors({ origin: origins, credentials: true }));
app.use(express.json({ limit: "2mb", verify: (req, _res, buf) => { req.rawBody = buf.toString(); } }));
app.use(express.urlencoded({ extended: true }));
app.get("/api/health", (_req, res) => res.json({ ok: true, uptime: Math.round(process.uptime()) }));
app.use("/uploads", express.static(UPLOAD_DIR, { maxAge: "7d" }));

app.use("/api/auth", authRoutes);
app.use("/api/posts", postRoutes);
app.use("/api/follow", followRoutes);
app.use("/api/likes", likesRoutes);
app.use("/api/ai", aiRoutes);
app.use("/api/conversation", conversationRoutes);
app.use("/api/stories", storyRoutes);
app.use("/api/subscriptions", subscriptionRoutes);
app.use("/api/admin", adminRoutes);
app.use("/api/upload", uploadRoutes);
app.use("/api/notifications", notificationRoutes);
app.get("/", (req, res) => res.status(200).json({ success: true, message: "Instagram Clone API is running 🚀" }));
app.use((err, req, res, _next) => { console.error(err); res.status(err.status || 500).json({ success: false, code: "SERVER_ERROR", message: err.message }); });
export default app;
