import express from "express";
import { protect } from "../middleware/auth.middleware.js";
import * as c from "../controllers/story.controller.js";
const r = express.Router();
r.use(protect);
r.post("/", c.createStory);
r.get("/feed", c.storyFeed);
r.get("/mine", c.myStories);
r.get("/user/:userId", c.userStories);
r.get("/highlights/:userId", c.listHighlights);
r.post("/highlights", c.createHighlight);
r.put("/highlights/:id", c.updateHighlight);
r.delete("/highlights/:id", c.deleteHighlight);
r.post("/:id/view", c.viewStory);
r.post("/:id/react", c.reactStory);
r.post("/:id/reply", c.replyStory);
r.get("/:id/analytics", c.storyAnalytics);
r.delete("/:id", c.deleteStory);
export default r;
